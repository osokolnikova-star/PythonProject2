a = int(input("Введиет количество строк: "))
b = int(input("Введите количество столбцов: "))
c = int(input("Введите номер записи: "))
e = (a*b) #Ищем, какоу количество строк и столбцов поместится на странице
#Находим станицу и место на странице
t = ((c-1) // e)
n = ((c-1) % e)
#Находим столбец и строку
p = (n // a)
m = (n % a)
print(f"{t+1}страница , {p+1}столбец , {m+1}строка")
